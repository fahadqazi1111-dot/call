/**
 * AI video scene — plays the generated clip composited over the stream
 * (screen blend melts the black background). If the clip is missing or
 * fails to load, falls back to the classic CSS scene automatically.
 */
function GiftVideoScene({ g }: { g: GiftAnim }) {
  const [failed, setFailed] = useState(false)
  if (failed || !g.video) return <GiftScene g={g} />
  return (
    <div className="absolute inset-0 overflow-hidden">
      {/* subtle vignette keeps the clip readable over bright video */}
      <div className="absolute inset-0 bg-[radial-gradient(circle_at_50%_55%,rgba(0,0,0,0.30),transparent_72%)]" />
      <video
        src={g.video}
        className="absolute left-1/2 top-1/2 w-[min(104vw,700px)] max-w-none -translate-x-1/2 -translate-y-1/2"
        style={{ mixBlendMode: 'screen' }}
        autoPlay
        muted
        playsInline
        onError={() => setFailed(true)}
      />
      <div className="absolute bottom-[10%] left-1/2 -translate-x-1/2">
        <GiftLabel g={g} />
      </div>
    </div>
  )
}

/** mounts its child after `delayMs` — the TikTok banner-then-anim beat */
function DelayedScene({ delayMs, children }: { delayMs: number; children: React.ReactNode }) {
  const [ready, setReady] = useState(delayMs <= 0)
  useEffect(() => {
    if (delayMs <= 0) return
    const t = window.setTimeout(() => setReady(true), delayMs)
    return () => window.clearTimeout(t)
  }, [delayMs])
  if (!ready) return null
  return <>{children}</>
}

/* ---------------- TikTok-style combo banner (right side) ---------------- */

interface ComboEntry {
  comboKey: string
  from: string
  to: string
  name: string
  emoji: string
  image: string | null
  tier: number
  count: number
  lastAt: number
  bump: number
}

const COMBO_WINDOW_MS = 6000

/**
 * Right-side stacked banner exactly like TikTok: “sender · Gift Name ×N”.
 * Same sender + same gift inside the window merges into one entry and the
 * ×N counter punches up (x2 → x3 → …) instead of stacking panels.
 */
function GiftComboBanner({ gifts }: { gifts: GiftAnim[] }) {
  const [combos, setCombos] = useState<ComboEntry[]>([])
  const mapRef = useRef(new Map<string, ComboEntry>())
  const seenRef = useRef(new Set<string>())

  // fold incoming gift events into combos
  useEffect(() => {
    for (const g of gifts) {
      if (seenRef.current.has(g.key)) continue
      seenRef.current.add(g.key)
      const comboKey = `${g.from}|${g.name}|${g.emoji}`
      const cur = mapRef.current.get(comboKey)
      if (cur && Date.now() - cur.lastAt < COMBO_WINDOW_MS) {
        mapRef.current.set(comboKey, { ...cur, count: cur.count + 1, lastAt: Date.now(), bump: cur.bump + 1 })
      } else {
        mapRef.current.set(comboKey, {
          comboKey,
          from: g.from,
          to: g.to,
          name: g.name,
          emoji: g.emoji,
          image: g.image ?? null,
          tier: g.tier,
          count: 1,
          lastAt: Date.now(),
          bump: 0,
        })
      }
    }
    setCombos(Array.from(mapRef.current.values()))
  }, [gifts])

  // expire combos shortly after the last send
  useEffect(() => {
    const t = window.setInterval(() => {
      const now = Date.now()
      const before = mapRef.current.size
      for (const [k, c] of mapRef.current) {
        if (now - c.lastAt > COMBO_WINDOW_MS + 600) mapRef.current.delete(k)
      }
      if (mapRef.current.size !== before) setCombos(Array.from(mapRef.current.values()))
    }, 700)
    return () => window.clearInterval(t)
  }, [])

  if (combos.length === 0) return null
  return (
    <div className="absolute right-3 top-[84px] z-30 flex w-[190px] flex-col items-end gap-2 sm:top-[92px]">
      {combos.slice(-3).map((c) => (
        <div
          key={c.comboKey}
          className="combo-in w-full rounded-2xl border border-white/20 bg-gradient-to-r from-[#1d1440]/95 via-[#5b2a86]/90 to-[#c2417f]/90 p-2.5 shadow-[0_10px_30px_rgba(0,0,0,0.45)] backdrop-blur"
        >
          <div className="flex items-center gap-2.5">
            {c.image ? (

              <img
                src={c.image}
                alt=""
                className="h-11 w-11 flex-none rounded-xl object-cover"
                style={{ mixBlendMode: 'screen' }}
                draggable={false}
              />
            ) : (
              <span className="flex h-11 w-11 flex-none items-center justify-center rounded-xl bg-white/15 text-[22px]">{c.emoji}</span>
            )}
            <div className="min-w-0 flex-1 leading-tight">
              <p className="truncate text-[12px] font-extrabold text-white">{c.from}</p>
              <p className="truncate text-[11.5px] font-bold text-[#FFD166]">
                {c.name} <span className="text-white/70">×{c.count}</span>
              </p>
            </div>
            <span key={c.bump} className="combo-count flex-none text-[16px] font-black text-[#FFD166] drop-shadow">
              ×{c.count}
            </span>
          </div>
        </div>
      ))}
    </div>
  )
}

export function GiftAnimationLayer({ gifts, showCombo = true }: { gifts: GiftAnim[]; showCombo?: boolean }) {
  // cap concurrent full-screen scenes so a gift burst never melts low-end phones
  const scenes = gifts.slice(-3)
  return (
    <div className="pointer-events-none absolute inset-0 z-40 overflow-hidden">
      {scenes.map((g) => (
        <div key={g.key} className="absolute inset-0">
          <DelayedScene delayMs={g.delayMs}>
            <GiftVideoScene g={g} />
          </DelayedScene>
        </div>
      ))}
      {showCombo && <GiftComboBanner gifts={gifts} />}
    </div>
  )
}

/** Play a delivered gift event (payload from REST fulfillment → socket relay). */
export function animFromPayload(payload: {
  sendId?: string
  gift: { name: string; emoji: string; animKind: string; durationMs: number; priceUsd?: number; imageUrl?: string | null }
  from: { name: string }
  to: { name: string }
}): GiftAnim {
  const price = payload.gift.priceUsd ?? 0
  const kind = payload.gift.animKind
  return {
    // key by the verified transaction id → duplicate events never re-render
    key: payload.sendId || `${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    emoji: payload.gift.emoji,
    name: payload.gift.name,
    animKind: kind,
    from: payload.from.name,
    to: payload.to.name,
    // full choreography length (delay + clip) so screens keep it mounted long enough
    durationMs: giftTotalMs(kind, payload.gift.durationMs, price),
    tier: tierOf(price),
    image: payload.gift.imageUrl ?? null,
    delayMs: giftDelayMs(kind, price),
    video: giftVideoFor(kind),
  }
}

export function soundTierFor(price: number): number {
  return Math.min(3, tierOf(price))
}

