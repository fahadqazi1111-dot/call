/* ---------------- gift video + timeline config ---------------- */

/**
 * AI-generated cinematic clips (black background → composited with screen
 * blend over the live video). Generated by scripts/gen-gift-videos.mjs.
 * A missing file falls back to the classic CSS scene — always safe.
 */
const GIFT_VIDEOS: Record<string, string> = {
  lion: '/gifts/videos/lion.mp4',
  superlion: '/gifts/videos/superlion.mp4',
  car: '/gifts/videos/car.mp4',
  dragon: '/gifts/videos/dragon.mp4',
  rocket: '/gifts/videos/rocket.mp4',
  fireworks: '/gifts/videos/fireworks.mp4',
  crown: '/gifts/videos/crown.mp4',
  castle: '/gifts/videos/castle.mp4',
  heart: '/gifts/videos/heart.mp4',
  rose: '/gifts/videos/rose.mp4',
}

const VIDEO_CLIP_MS = 5400

export function giftVideoFor(kind: string): string | null {
  return GIFT_VIDEOS[kind] ?? null
}

/**
 * TikTok choreography: the side banner appears instantly, then the big
 * animation hits after a short dramatic pause (2-3s for the heavy gifts,
 * quick hit for small ones). No clip for this kind → play immediately.
 */
export function giftDelayMs(kind: string, priceUsd = 0): number {
  if (!GIFT_VIDEOS[kind]) return 0
  if (kind === 'lion' || kind === 'superlion') return 2500
  if (priceUsd >= 5) return 1800
  return 700
}

/** total time the animation stays mounted (delay + clip or CSS duration) */
export function giftTotalMs(kind: string, durationMs: number, priceUsd = 0): number {
  const delay = giftDelayMs(kind, priceUsd)
  if (!GIFT_VIDEOS[kind]) return durationMs
  return Math.max(durationMs, delay + VIDEO_CLIP_MS)
}

/* ---------------- animation layer (per-gift cinematic scenes) ---------------- */

function tierOf(price: number): number {
  if (price >= 30) return 3
  if (price >= 5) return 2
  return 1
}

/** deterministic pseudo-random per gift instance, so server & client layouts differ nicely */
function seeded(n: number): number {
  const x = Math.sin(n) * 10000
  return x - Math.floor(x)
}

